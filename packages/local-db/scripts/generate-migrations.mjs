// Turns the SQL files that drizzle-kit writes into one TypeScript module the app can bundle.
// Metro cannot import `.sql` files, and the app needs the statements at runtime (spec 7.7).
// Run after every `drizzle-kit generate`: `pnpm --filter @muslim-give/local-db db:generate` does both.
// A test fails if the generated module is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const journal = JSON.parse(readFileSync(join(root, 'migrations/meta/_journal.json'), 'utf8'));

const migrations = journal.entries.map((entry) => {
  const sql = readFileSync(join(root, 'migrations', `${entry.tag}.sql`), 'utf8');
  const statements = sql
    .split('--> statement-breakpoint')
    .map((statement) => statement.trim())
    .filter((statement) => statement.length > 0);
  return { tag: entry.tag, statements };
});

const body = migrations
  .map(
    (m) =>
      `  {\n    tag: ${JSON.stringify(m.tag)},\n    statements: [\n${m.statements
        .map((s) => `      ${JSON.stringify(s)},`)
        .join('\n')}\n    ],\n  },`,
  )
  .join('\n');

writeFileSync(
  join(root, 'src/migrations.generated.ts'),
  `// Generated by scripts/generate-migrations.mjs from migrations/. Do not edit.\n` +
    `import type { Migration } from './migrate.js';\n\n` +
    `export const MIGRATIONS: readonly Migration[] = [\n${body}\n];\n`,
);
