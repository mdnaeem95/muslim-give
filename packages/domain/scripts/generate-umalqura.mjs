// Generates src/hijri/umalqura-data.ts from Node's full-ICU `islamic-umalqura` calendar.
// Run: node scripts/generate-umalqura.mjs   (spec R-HIJ-06, ADR-007)
// The oracle test re-checks every day against ICU, so a stale file fails CI.
import { writeFileSync } from 'node:fs';

const FIRST_YEAR = 1356;
const LAST_YEAR = 1500;
const MS_PER_DAY = 86_400_000;

const fmt = new Intl.DateTimeFormat('en-u-ca-islamic-umalqura-nu-latn', {
  year: 'numeric',
  month: 'numeric',
  day: 'numeric',
  timeZone: 'UTC',
});
const hijriOf = (epochDay) => {
  const parts = fmt.formatToParts(new Date(epochDay * MS_PER_DAY));
  const get = (t) => Number(parts.find((p) => p.type === t).value);
  return { year: get('year'), month: get('month'), day: get('day') };
};

// 1 Muharram 1356 AH is 1937-03-14; scan forward from a few days earlier to find it.
let epochDay = Math.floor(Date.UTC(1937, 2, 10) / MS_PER_DAY);
while (true) {
  const h = hijriOf(epochDay);
  if (h.year === FIRST_YEAR && h.month === 1 && h.day === 1) break;
  epochDay += 1;
  if (epochDay > 20_000) throw new Error('could not find 1 Muharram 1356');
}
const firstStart = epochDay;

let lengths = '';
let year = FIRST_YEAR;
let month = 1;
while (year <= LAST_YEAR) {
  let length = 0;
  let h = hijriOf(epochDay);
  if (h.year !== year || h.month !== month || h.day !== 1) {
    throw new Error(`unexpected month start at ${epochDay}: ${JSON.stringify(h)}`);
  }
  while (h.year === year && h.month === month) {
    length += 1;
    epochDay += 1;
    h = hijriOf(epochDay);
  }
  if (length !== 29 && length !== 30) throw new Error(`bad month length ${length}`);
  lengths += length === 30 ? '1' : '0';
  month += 1;
  if (month === 13) {
    month = 1;
    year += 1;
  }
}

const out = `// GENERATED by scripts/generate-umalqura.mjs from ICU ${process.versions.icu}. Do not edit.
// Umm al-Qura month lengths for ${FIRST_YEAR}-${LAST_YEAR} AH (spec R-HIJ-06).

export const UMALQURA_FIRST_YEAR = ${FIRST_YEAR};
export const UMALQURA_LAST_YEAR = ${LAST_YEAR};
/** Days since 1970-01-01 of 1 Muharram ${FIRST_YEAR} AH. */
export const UMALQURA_FIRST_EPOCH_DAY = ${firstStart};
/** One character per month, oldest first: '1' = 30 days, '0' = 29 days. */
export const UMALQURA_MONTH_LENGTHS =
  '${lengths}';
`;
writeFileSync(new URL('../src/hijri/umalqura-data.ts', import.meta.url), out);
process.stdout.write(
  `first=${firstStart} months=${lengths.length} end epochDay=${epochDay} icu=${process.versions.icu}\n`,
);
